import assert from 'node:assert/strict';
import {buildSalesReportModel, filterMarkup, tableMarkup} from './out/assets/daily-sales.mjs';

const period = {year:2026,month:9,latest_date:'2026-09-16',dates:['2026-09-16'],branches:[{branch:'Test store',branch_code:'T01',type:'CDS',target:1000,month_to_date:100,daily_sales:{'2026-09-16':100}}]};
const report = {periods:{'2026-09':period}};
const state = {year:2026,month:'2026-09'};
const model = date => buildSalesReportModel(report,{...state,date},'2026-09-20');
assert.equal(model('latest').selectedDate,'2026-09-16');
assert.equal(model('latest').dates.length,30);
assert.match(filterMarkup(model('latest')),/value="latest" selected/);
assert.match(filterMarkup(model('latest')),/value="2026-09-30"/);
const close = model('month-end');
assert.equal(close.selectedDate,'');
assert.equal(close.summary.total,100);
assert.equal(close.monthComplete,false);
assert.match(filterMarkup(close),/value="month-end" selected/);
assert.match(filterMarkup(close),/รอข้อมูลครบเดือน/);
const future = model('2026-09-30');
assert.equal(future.totals.daily,null,'An unreported day must not become zero');
assert.equal(future.totals.rows[0].daily,null);
assert.match(filterMarkup(future),/value="2026-09-30" selected/);
assert.match(tableMarkup(future,{},'2026-09-20'),/—/);
period.latest_date='2026-09-19';
period.dates.push('2026-09-19');
period.branches[0].daily_sales['2026-09-19']=50;
period.branches[0].month_to_date=150;
assert.equal(model('latest').selectedDate,'2026-09-19','Follow new dates automatically');
assert.equal(model('2026-09-16').selectedDate,'2026-09-16','Keep explicitly selected historical dates');
assert.equal(model('month-end').summary.total,150,'Month-end totals receive new source amounts');
const completed=structuredClone(report);
completed.periods['2026-09'].latest_date='2026-09-30';
completed.periods['2026-09'].dates.push('2026-09-30');
completed.periods['2026-09'].branches[0].daily_sales['2026-09-30']=0;
const closed=buildSalesReportModel(completed,{...state,date:'month-end'},'2026-10-01');
assert.equal(closed.monthComplete,true);
assert.doesNotMatch(filterMarkup(closed),/รอข้อมูลครบเดือน/);
const february={periods:{'2024-02':{...period,year:2024,month:2,dates:[],latest_date:null}}};
assert.equal(buildSalesReportModel(february,{year:2024,month:'2024-02',date:'month-end'},'2026-09-20').monthEnd,'2024-02-29');
console.log('Month-end, leap year, missing days, latest-date tracking and explicit-date preservation passed.');
